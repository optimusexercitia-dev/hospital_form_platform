#!/usr/bin/env node
/**
 * features:index — generate docs/features/INDEX.md and the PROGRESS.md feature roll-up from
 * hub frontmatter (ADR 0185 D1 / D6). Same shape as build-adr-index.mjs: a generated artifact
 * whose source and output must agree, byte-compared by `--check` (run by `lint:registers`).
 *
 *   node scripts/build-features-index.mjs --write   # rewrite both artifacts
 *   node scripts/build-features-index.mjs --check   # exit 1 on drift
 *
 * The roll-up in PROGRESS.md lives between two marker comments inside § Phase Status and
 * lists LIVE hubs only (complete hubs stay in INDEX.md) — gate 7's PHASES check reds on a
 * "complet…" Status cell in that section, and that is the right outcome: a completed unit's
 * home is the ledger and the index, not the live tracker.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, basename } from 'node:path'
import { pathToFileURL } from 'node:url'
import { listHubs, ROOT, PATHS } from './check-docs-registers.mjs'

export const START_PREFIX = '<!-- features-rollup:start'
export const START = `${START_PREFIX} — generated by scripts/build-features-index.mjs, do not edit -->`
export const END = '<!-- features-rollup:end -->'

const STATUS_RANK = { in_progress: 0, gated: 1, planned: 2, parked: 3, complete: 4 }
const STATUS_LABEL = {
  in_progress: '🟢 in progress',
  gated: '🚧 gated',
  planned: '🔜 planned',
  parked: '⏸ parked',
  complete: '✅ complete',
}

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')
const branchCell = (fm) => (fm.branch ? `\`${fm.branch}\`` : '—')
const label = (fm) => STATUS_LABEL[fm.status] ?? fm.status
const count = (hubs, s) => hubs.filter((h) => h.fm?.status === s).length

export function sorted(hubs) {
  return [...hubs]
    .filter((h) => h.fm && h.fm.id)
    .sort((a, b) => (STATUS_RANK[a.fm.status] ?? 9) - (STATUS_RANK[b.fm.status] ?? 9) || String(a.fm.id).localeCompare(String(b.fm.id)))
}

export function renderIndex(hubs) {
  const rows = sorted(hubs).map(
    (h) => `| ${h.fm.id} | ${esc(h.fm.title)} | ${label(h.fm)} | ${h.fm.kind} | ${h.fm.program ?? '—'} | ${branchCell(h.fm)} | [${basename(h.file)}](${basename(h.file)}) |`,
  )
  return [
    '# Feature hubs — index',
    '',
    "> ⚙ **GENERATED FILE — do not edit by hand.** Every row is derived from a hub's YAML frontmatter",
    '> (`docs/features/<slug>.md`). Rebuild with `npm run features:index`; `npm run lint:registers`',
    '> (gate 13 of `npm run lint`) reds when this file is out of date. ADR 0185 D1.',
    '>',
    '> A hub exists **before** a branch is cut. Codes for historical work that never had a hub:',
    '> [legacy-codes.md](legacy-codes.md). The live working state of an in-progress hub is its',
    '> `## Current state` block; the list of in-progress hubs is',
    '> [../planning/CURRENT.md](../planning/CURRENT.md).',
    '',
    `**${rows.length} hubs** · in progress ${count(hubs, 'in_progress')} · gated ${count(hubs, 'gated')} · planned ${count(hubs, 'planned')} · parked ${count(hubs, 'parked')} · complete ${count(hubs, 'complete')}`,
    '',
    '| ID | Title | Status | Kind | Program | Branch | Hub |',
    '|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n')
}

export function renderRollup(hubs) {
  const live = sorted(hubs).filter((h) => h.fm.status !== 'complete')
  const rows = live.map((h) => `| ${h.fm.id} | ${esc(h.fm.title)} | ${label(h.fm)} | ${branchCell(h.fm)} | [hub](${h.file}) |`)
  return [START, '', '| Feature | Title | Status | Branch | Hub |', '|---|---|---|---|---|', ...rows, '', END].join('\n')
}

/** Replace the marker block in PROGRESS.md; null when the markers are absent or inverted. */
export function spliceRollup(progressText, block) {
  const s = progressText.indexOf(START_PREFIX)
  const e = progressText.indexOf(END)
  if (s === -1 || e === -1 || e < s) return null
  return progressText.slice(0, s) + block + progressText.slice(e + END.length)
}

function main() {
  const mode = process.argv.includes('--write') ? 'write' : process.argv.includes('--check') ? 'check' : null
  if (!mode) {
    console.error('usage: build-features-index.mjs --write | --check')
    process.exit(2)
  }
  const hubs = listHubs()
  const bad = hubs.filter((h) => !h.fm)
  if (bad.length) {
    console.error(`build-features-index: ${bad.length} hub(s) without parseable frontmatter — lint:registers reports which`)
    process.exit(1)
  }
  const indexPath = join(ROOT, PATHS.featuresIndex)
  const progressPath = join(ROOT, 'PROGRESS.md')
  const wantIndex = renderIndex(hubs)
  const progress = readFileSync(progressPath, 'utf8')
  const wantProgress = spliceRollup(progress, renderRollup(hubs))
  if (wantProgress == null) {
    console.error(`build-features-index: PROGRESS.md lacks the roll-up markers (${START_PREFIX} … ${END}) — add them inside § Phase Status`)
    process.exit(1)
  }
  if (mode === 'write') {
    writeFileSync(indexPath, wantIndex)
    if (wantProgress !== progress) writeFileSync(progressPath, wantProgress)
    console.log(`build-features-index: wrote ${PATHS.featuresIndex} (${hubs.length} hubs) and the PROGRESS.md roll-up`)
    return
  }
  const haveIndex = existsSync(indexPath) ? readFileSync(indexPath, 'utf8') : null
  const drift = []
  if (haveIndex !== wantIndex) drift.push(PATHS.featuresIndex)
  if (wantProgress !== progress) drift.push('PROGRESS.md roll-up')
  if (drift.length) {
    console.error(`build-features-index: STALE — ${drift.join(', ')}; run \`npm run features:index\``)
    process.exit(1)
  }
  console.log(`build-features-index: OK (${hubs.length} hubs; index and roll-up in sync)`)
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main()
