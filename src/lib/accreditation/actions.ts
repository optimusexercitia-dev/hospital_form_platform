// --- form-field parsing helpers -------------------------------------------

function requiredString(formData: FormData, key: string): string {
  return String(formData.get(key) ?? '').trim()
}

function optionalString(formData: FormData, key: string): string | undefined {
  const value = requiredString(formData, key)
  return value || undefined
}

/**
 * A dedicated read for `note_md`-shaped fields backed by a `coalesce(p_x,
 * x)`-style RPC upsert (BUG-P16-001) — `optionalString`'s `'' -> undefined`
 * collapse makes "the user cleared this field" indistinguishable from "this
 * field was never in the submission" at the RPC boundary: `undefined` is
 * dropped from the JSON body entirely, so `coalesce(p_note_md, note_md)`
 * keeps the OLD value, silently discarding an intentional clear. This
 * preserves the distinction instead: a genuinely absent field (`formData.get`
 * returns `null` — not the case for an always-rendered textarea today, but
 * kept correct for a future conditional/disabled render) stays `undefined`
 * (RPC leaves the note untouched); a present-but-emptied field returns `''`
 * (RPC's `coalesce('', note_md)` overwrites with empty — an explicit clear).
 * Deliberately NOT a change to `optionalString` itself — every other caller
 * in this file (`version`/`description`/`descriptionMd`/`parentId`/`note`)
 * keeps the collapse; see the file-level BUG-P16-001 note on
 * `setStandardAssessment` for why only THIS field needed the distinction.
 */
function optionalClearableText(formData: FormData, key: string): string | undefined {
  const raw = formData.get(key)
  if (raw === null) return undefined
  return String(raw).trim()
}

function parseOptionalPosition(raw: FormDataEntryValue | null): number | undefined {
  const s = String(raw ?? '').trim()
  if (!s) return undefined
  const n = Number(s)
  return Number.isFinite(n) ? n : undefined
}

function parseOptionalLevel(raw: FormDataEntryValue | null): StandardLevel | undefined | null {
  const s = String(raw ?? '').trim()
  if (!s) return undefined
  const n = Number(s)
  return n === 1 || n === 2 || n === 3 ? (n as StandardLevel) : null // null = invalid
}

