/**
 * Set (upsert) a commission's self-assessment for one standard. `noteMd`
 * carries the standing PHI-discouragement copy on its field (D8), enforced
 * at the UI layer. Routes to `set_standard_assessment`.
 *
 * BUG-P16-001 (data loss, fixed): the RPC's upsert does
 * `note_md = coalesce(p_note_md, note_md)` so a re-save with the note field
 * untouched preserves the existing note — but that same coalesce meant an
 * INTENTIONAL clear (empty the textarea, save) was indistinguishable from
 * "field not submitted" once `optionalString`'s `'' -> undefined` collapse
 * ran, so the clear silently no-opped instead of reaching the RPC. Fixed on
 * both sides: backend's RPC now treats `''` (not just non-null) as "set to
 * empty" vs `NULL`/omitted as "leave alone"; this action reads `noteMd` via
 * {@link optionalClearableText} instead of {@link optionalString} so an
 * emptied textarea sends `''` through, not `undefined`.
 */
export async function setStandardAssessment(
  _prev: ActionState | undefined,
  formData: FormData,
): Promise<ActionState> {
  const commissionId = requiredString(formData, 'commissionId')
  const standardId = requiredString(formData, 'standardId')
  const status = requiredString(formData, 'status') as AssessmentStatus
  const noteMd = optionalClearableText(formData, 'noteMd')

  if (!commissionId) return { ok: false, error: MESSAGES.commissionNotFound }
  if (!standardId) return { ok: false, error: MESSAGES.standardNotFound }
  if (!status) return { ok: false, fieldErrors: { status: MESSAGES.assessmentStatusRequired } }

  const supabase = await createClient()
  const { error } = await supabase.rpc('set_standard_assessment', {
    p_commission: commissionId,
    p_standard: standardId,
    p_status: status,
    p_note_md: noteMd,
  })

  if (error) return { ok: false, error: mapAccreditationError(error) }

  revalidateAccreditation()
  return { ok: true, error: MESSAGES.assessmentSaved }
}

